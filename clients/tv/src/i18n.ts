const TABLES: Record<Lang, Record<string, string>> = { en: {}, es: ES };

function detect(): Lang {
  // Only real strings: on Apple TV (NativeScript) these globals can hold other values.
  const pick = (v: unknown): Lang | null => {
    const l = typeof v === "string" ? v.toLowerCase() : "";
    return l.startsWith("es") ? "es" : l.startsWith("en") ? "en" : null;
  };
  let stored: string | null = null;
  try {
    stored = globalThis.localStorage?.getItem("panda.lang") ?? null;
  } catch {
    // Storage unavailable: use the device language.
  }
  // Outside a browser (tests) there's no location or navigator: English.
  if (typeof location === "undefined") return "en";
  const fromUrl =
    new URLSearchParams(location.search).get("lang") ??
    new URLSearchParams(location.hash.split("?")[1] ?? "").get("lang");
  return pick(fromUrl) ?? pick(stored) ?? pick(navigator.language) ?? "en";
}

/** The device's language (URL/storage override, else the TV/browser setting). */
export const deviceLang = detect;
export const [lang, setLang] = createSignal<Lang>(detect());

/** The text in the current language, with `{placeholders}` filled in. */
export function t(text: string, params?: Record<string, string | number>): string {
  const out = TABLES[lang()][text] ?? text;
  return params ? out.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : out;
}

/** Plural helper: `tn(3, "{n} season", "{n} seasons")`. */
export function tn(n: number, one: string, many: string): string {
  return t(n === 1 ? one : many, { n });
}

/** Row titles the server sends in English ("Trending this week", "Popular on Netflix"). */
export function tServer(title: string): string {
  const popular = /^Popular on (.+)$/.exec(title);
  return popular ? t("Popular on {name}", { name: popular[1] }) : t(title);
}
